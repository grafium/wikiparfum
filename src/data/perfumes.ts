export const getPerfumeById = (id: string): Perfume | undefined => {
  return perfumes.find(perfume => perfume.id === id);
};

export const getPerfumeBySlug = (slug: string): Perfume | undefined => {
  return perfumes.find(perfume => perfume.slug === slug);
};

export const getPerfumesByBrand = (brandId: string): Perfume[] => {
  return perfumes.filter(perfume => perfume.brandId === brandId);
};

export const searchPerfumes = (query: string): Perfume[] => {
  const lowerQuery = query.toLowerCase();
  return perfumes.filter(perfume => 
    perfume.name.toLowerCase().includes(lowerQuery) ||
    perfume.description.toLowerCase().includes(lowerQuery) ||
    perfume.accords.some(accord => accord.toLowerCase().includes(lowerQuery))
  );
};

export const getRandomPerfume = (): Perfume => {
  return perfumes[Math.floor(Math.random() * perfumes.length)];
};

export const getPopularPerfumes = (limit: number = 8): Perfume[] => {
  // In a real app, this would be based on actual popularity metrics
  return perfumes.slice(0, limit);
};

export const getSimilarPerfumes = (perfume: Perfume, limit: number = 4): Perfume[] => {
  return perfumes
    .filter(p => 
      p.id !== perfume.id && 
      (p.family === perfume.family || p.accords.some(a => perfume.accords.includes(a)))
    )
    .slice(0, limit);
};
